// else if condition
let number = 17.5;

if (number >= 18 && number <= 20) {
  console.log("Good job");
} else if (number >= 15 && number <= 18) {
  console.log("Good");
} else if (number >= 12 && number <= 15) {
  console.log("Need for effort");
} else if (number >= 0 && number <= 12) {
  console.log("Bad");
} else {
  console.log("Invalid Number");
}
